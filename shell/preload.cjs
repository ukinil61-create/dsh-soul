// 页面只能说话和收事件，拿不到令牌，也碰不到系统。
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('soulHost', {
  pathFor: (file) => webUtils.getPathForFile(file),
  dragOver: (over) => ipcRenderer.send('soul:drag-over', over),
  drop: (paths) => ipcRenderer.send('soul:drop', paths),
  say: (text) => ipcRenderer.send('soul:say', text),
  cancel: () => ipcRenderer.send('soul:cancel'),
  dismiss: () => ipcRenderer.send('soul:dismiss'),
  summon: () => ipcRenderer.send('soul:summon'),
  ready: () => ipcRenderer.send('soul:ready'),
  audioEnded: (id) => ipcRenderer.send('soul:audio-ended', id),
  caption: (text, ms) => ipcRenderer.send('soul:caption', text, ms),
  micChunk: (samples) => ipcRenderer.send('soul:mic', samples),
  closePanel: () => ipcRenderer.send('soul:close-panel'),
  toggleDrawer: () => ipcRenderer.send('soul:toggle-drawer'),
  panelDrag: (edge) => ipcRenderer.send('soul:panel-drag', edge),
  desktopKey: (key) => ipcRenderer.send('soul:desktop-key', key),
  openStudio: () => ipcRenderer.send('soul:open-studio'),
  minimaxVoices: () => ipcRenderer.invoke('soul:minimax-voices'),
  figuresList: () => ipcRenderer.invoke('soul:figures-list'),
  figureSave: (spec) => ipcRenderer.invoke('soul:figure-save', spec),
  figureDelete: (name) => ipcRenderer.invoke('soul:figure-delete', name),
  figureUse: (choice) => ipcRenderer.invoke('soul:figure-use', choice),
  getSettings: () => ipcRenderer.invoke('soul:settings-get'),
  setSetting: (key, value) => ipcRenderer.invoke('soul:settings-set', key, value),
  voiceTest: () => ipcRenderer.send('soul:voice-test'),
  openOfficial: () => ipcRenderer.invoke('soul:official-open'),
  closeOfficial: () => ipcRenderer.send('soul:official-close'),
  openRecords: () => ipcRenderer.send('soul:open-records'),
  pasteImage: (bytes) => ipcRenderer.invoke('soul:paste-image', bytes),
  pickFolder: () => ipcRenderer.invoke('soul:pick-folder'),
  api: (route, body) => ipcRenderer.invoke('soul:api', route, body),
  onEvent: (listener) => ipcRenderer.on('soul:event', (_event, payload) => listener(payload)),
});
